/**
 * The icon set. Lucide geometry, drawn inline so there is no runtime dependency
 * and no icon font.
 *
 * All of these are decorative — every one sits next to a text label that already
 * says the same thing — so they are `aria-hidden` by default and contribute
 * nothing to an accessible name. A 24×24 box and a 1.5 stroke throughout; do not
 * mix in a second weight.
 */

import type { ReactNode } from 'react';

interface IconProps {
  size?: number;
  className?: string;
}

function Svg({ size = 16, className, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {children}
    </svg>
  );
}

